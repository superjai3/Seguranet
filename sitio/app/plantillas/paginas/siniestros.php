    <div class="sn-contenedor sn-medido">
        <h1>Tuviste un siniestro</h1>
        <p style="font-size:var(--sn-txt-lg)">
            Lo primero: hay plazos que corren desde el momento del hecho. Esta página
            te dice qué hacer y en cuánto tiempo.
        </p>

        <div class="sn-aviso sn-aviso--dato">
            <strong>El plazo clave son 3 días.</strong>
            El art. 46 de la Ley 17.418 obliga a denunciar el siniestro a la aseguradora
            dentro de los tres días de conocido. Denunciar tarde puede costarte la cobertura.
        </div>

        <h2>En el momento</h2>
        <ol>
            <li>Ponete a salvo y, si hay heridos, llamá al 107 antes que a nadie.</li>
            <li>No muevas los vehículos hasta sacar fotos, salvo que obstruyan el tránsito o haya peligro.</li>
            <li>Sacá fotos de los daños, de las patentes, del lugar y de la posición de los autos.</li>
            <li>Intercambiá con el tercero: nombre, DNI, teléfono, aseguradora y número de póliza.</li>
            <li>Si hay heridos, delito o el tercero se va, hacé la denuncia policial.</li>
            <li>No firmes reconocimientos de culpa ni acuerdos en el lugar.</li>
        </ol>

        <h2>Dentro de los 3 días</h2>
        <ol>
            <li>Denunciá el siniestro a tu aseguradora, por su canal oficial.</li>
            <li>Guardá el número de denuncia: todo lo que venga después se sigue con ese número.</li>
            <li>Avisanos a nosotros, para acompañarte en lo que sigue.</li>
        </ol>

        <h2>Qué documentación te van a pedir</h2>
        <ul>
            <li>Póliza vigente y último comprobante de pago.</li>
            <li>Licencia de conducir del que manejaba, vigente al momento del hecho.</li>
            <li>Cédula verde o azul del vehículo.</li>
            <li>DNI del titular y del conductor.</li>
            <li>Denuncia policial, cuando corresponda.</li>
            <li>Fotos de los daños y datos del tercero.</li>
        </ul>

        <h2>Después de la denuncia</h2>
        <p>
            La aseguradora tiene <strong>30 días</strong> para pronunciarse sobre el
            derecho del asegurado (art. 56, Ley 17.418). Si guarda silencio, la ley
            entiende que aceptó el siniestro. Si rechaza, tiene que decirte por qué.
        </p>

